// --- CLOCK & CALENDAR ---
let currentCalDate = new Date();

function initClockAndCalendar() {
  function updateClock() {
    const now = new Date();
    const clockEl = document.getElementById("liveClock");
    const dateEl = document.getElementById("liveDateShort");

    if (clockEl) {
      clockEl.textContent = now.toLocaleTimeString([], { hour12: false });
    }
    if (dateEl) {
      dateEl.textContent = now.toLocaleDateString(undefined, {
        weekday: "long",
        month: "short",
        day: "numeric",
        year: "numeric"
      });
    }
  }

  setInterval(updateClock, 1000);
  updateClock();
  renderCalendar(currentCalDate);

  document.getElementById("prevMonthBtn").addEventListener("click", () => {
    currentCalDate.setMonth(currentCalDate.getMonth() - 1);
    renderCalendar(currentCalDate);
  });

  document.getElementById("nextMonthBtn").addEventListener("click", () => {
    currentCalDate.setMonth(currentCalDate.getMonth() + 1);
    renderCalendar(currentCalDate);
  });
}

function renderCalendar(date) {
  const monthYearLabel = document.getElementById("calendarMonthYear");
  const daysContainer = document.getElementById("calendarDays");
  if (!daysContainer || !monthYearLabel) return;

  daysContainer.innerHTML = "";
  const year = date.getFullYear();
  const month = date.getMonth();

  monthYearLabel.textContent = date.toLocaleDateString(undefined, { month: "long", year: "numeric" });

  const firstDayIndex = new Date(year, month, 1).getDay();
  const totalDays = new Date(year, month + 1, 0).getDate();
  const today = new Date();

  for (let i = 0; i < firstDayIndex; i++) {
    const empty = document.createElement("div");
    daysContainer.appendChild(empty);
  }

  for (let day = 1; day <= totalDays; day++) {
    const dayEl = document.createElement("div");
    dayEl.className = "py-1.5 rounded-lg text-slate-300 hover:bg-slate-800 transition cursor-pointer text-xs";
    dayEl.textContent = day;

    if (
      day === today.getDate() &&
      month === today.getMonth() &&
      year === today.getFullYear()
    ) {
      dayEl.classList.add("calendar-today");
    }

    daysContainer.appendChild(dayEl);
  }
}

